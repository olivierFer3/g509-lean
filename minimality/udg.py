"""Basic tools for unit-distance graphs (UDG) in the plane.

- EXACT arithmetic in K = Q(sqrt3, sqrt5, sqrt11) (field of the coordinates
  of the points generated by the rotations w1 (60°), w3 (cos=5/6), w4 (cos=7/8)).
- Graph construction: candidates found in floating point, then EACH edge
  confirmed exactly (|p-q|^2 == 1 in K).
- Coloring check, chromatic number by brute force (small cases),
  k-colorability by SAT (pysat / CaDiCaL).
"""
from fractions import Fraction as F
from itertools import product
import math

PR = (3, 5, 11)  # sqrt(3), sqrt(5), sqrt(11)

def _mult(m1, m2):
    c = 1
    for i, p in enumerate(PR):
        if (m1 >> i) & 1 and (m2 >> i) & 1:
            c *= p
    return m1 ^ m2, c

class K:
    """Element of Q(sqrt3,sqrt5,sqrt11): tuple of 8 rationals indexed by a bit mask (bit i = sqrt(PR[i]))."""
    __slots__ = ("c",)
    def __init__(self, c):
        self.c = tuple(c)
    @staticmethod
    def rat(q):
        return K([F(q)] + [F(0)] * 7)
    @staticmethod
    def sqrt(p, coef=1):
        v = [F(0)] * 8; v[1 << PR.index(p)] = F(coef); return K(v)
    def __add__(s, o): return K(a + b for a, b in zip(s.c, o.c))
    def __sub__(s, o): return K(a - b for a, b in zip(s.c, o.c))
    def __neg__(s): return K(-a for a in s.c)
    def __mul__(s, o):
        r = [F(0)] * 8
        for m1, a in enumerate(s.c):
            if a == 0: continue
            for m2, b in enumerate(o.c):
                if b == 0: continue
                m, k = _mult(m1, m2); r[m] += a * b * k
        return K(r)
    def __eq__(s, o): return s.c == o.c
    def __hash__(s): return hash(s.c)
    def is_zero(s): return all(a == 0 for a in s.c)
    def __float__(s):
        t = 0.0
        for m, a in enumerate(s.c):
            if a:
                t += float(a) * math.sqrt(math.prod(p for i, p in enumerate(PR) if (m >> i) & 1))
        return t

ZERO, ONE = K.rat(0), K.rat(1)

class P:
    """Exact point (x, y) with x, y in K; also seen as the complex number x+iy."""
    __slots__ = ("x", "y")
    def __init__(s, x, y): s.x, s.y = x, y
    def __add__(s, o): return P(s.x + o.x, s.y + o.y)
    def __sub__(s, o): return P(s.x - o.x, s.y - o.y)
    def __mul__(s, o):  # complex product
        return P(s.x * o.x - s.y * o.y, s.x * o.y + s.y * o.x)
    def conj(s): return P(s.x, -s.y)
    def norm2(s): return s.x * s.x + s.y * s.y
    def __eq__(s, o): return s.x == o.x and s.y == o.y
    def __hash__(s): return hash((s.x, s.y))
    def c(s): return complex(float(s.x), float(s.y))

# Exact unit rotations
W1 = P(K.rat(F(1, 2)), K.sqrt(3, F(1, 2)))     # e^{i pi/3}
W3 = P(K.rat(F(5, 6)), K.sqrt(11, F(1, 6)))    # cos = 5/6, sin = sqrt(11)/6
# sin = sqrt(15)/8 = sqrt3*sqrt5/8 : masque 0b011
W4 = P(K.rat(F(7, 8)), K([F(0), F(0), F(0), F(1, 8), F(0), F(0), F(0), F(0)]))
# eta = exp(i/2 * arccos 5/6) = (sqrt33 + i sqrt3)/6: HALF-angle of the Moser spindle
# (the rotation called eta by Parts; eta^2 = W3). sqrt33 = mask 0b101.
ETA = P(K([F(0), F(0), F(0), F(0), F(0), F(1, 6), F(0), F(0)]), K.sqrt(3, F(1, 6)))
P0 = P(ZERO, ZERO)
P1 = P(ONE, ZERO)

def rpow(w, n):
    r = P1
    b = w if n >= 0 else w.conj()   # |w| = 1 hence w^{-1} = conj(w)
    for _ in range(abs(n)): r = r * b
    return r

def unit_graph(points, exact=True, tol=1e-7):
    """Edges {i,j} with |p_i - p_j| = 1. points: list of P (exact) or of complex numbers."""
    zs = [p.c() if isinstance(p, P) else complex(p) for p in points]
    grid = {}
    for i, z in enumerate(zs):
        grid.setdefault((math.floor(z.real), math.floor(z.imag)), []).append(i)
    edges = []
    for i, z in enumerate(zs):
        gx, gy = math.floor(z.real), math.floor(z.imag)
        for dx, dy in product((-1, 0, 1), repeat=2):
            for j in grid.get((gx + dx, gy + dy), ()):
                if j <= i: continue
                if abs(abs(z - zs[j]) - 1) < tol:
                    if exact and isinstance(points[i], P):
                        d = (points[i] - points[j]).norm2()
                        if not (d - ONE).is_zero():
                            continue  # floating-point false positive (never observed)
                    edges.append((i, j))
    return edges

def check_coloring(n, edges, col):
    """True if col (list of n colors) is proper: no monochromatic edge."""
    return len(col) == n and all(col[u] != col[v] for u, v in edges)

def brute_chromatic(n, edges, kmax=6):
    """Chromatic number by simple backtracking (small graphs only)."""
    adj = [[] for _ in range(n)]
    for u, v in edges: adj[u].append(v); adj[v].append(u)
    def colorable(k):
        col = [-1] * n
        def bt(i):
            if i == n: return True
            used = {col[j] for j in adj[i] if col[j] >= 0}
            top = max(col[:i], default=-1)  # breaks the symmetry of the colors
            for c in range(min(k, top + 2)):
                if c not in used:
                    col[i] = c
                    if bt(i + 1): return True
            col[i] = -1
            return False
        return bt(0), col
    for k in range(1, kmax + 1):
        ok, col = colorable(k)
        if ok: return k, col
    return None, None

def sat_colorable(n, edges, k, return_coloring=False, solver="cadical153", fix=None):
    """SAT test of k-colorability. Variables x[v][c] = v*k+c+1.
    Clauses: each vertex has >= 1 color; each edge: not the same color.
    ("at most one color" is unnecessary: one can always keep a single one.)
    fix: list of vertices of a clique whose colors are fixed to 0,1,2,...
    (valid symmetry breaking because the colors are interchangeable)."""
    from pysat.solvers import Solver
    var = lambda v, c: v * k + c + 1
    with Solver(name=solver) as s:
        for v in range(n):
            s.add_clause([var(v, c) for c in range(k)])
        for u, v in edges:
            for c in range(k):
                s.add_clause([-var(u, c), -var(v, c)])
        if fix:
            for c, v in enumerate(fix):
                s.add_clause([var(v, c)])
        ok = s.solve()
        if ok and return_coloring:
            m = set(l for l in s.get_model() if l > 0)
            col = [next(c for c in range(k) if var(v, c) in m) for v in range(n)]
            return True, col
        return ok, None

def find_triangle(n, edges):
    adj = [set() for _ in range(n)]
    for u, v in edges: adj[u].add(v); adj[v].add(u)
    for u, v in edges:
        w = adj[u] & adj[v]
        if w: return [u, v, min(w)]
    return None
