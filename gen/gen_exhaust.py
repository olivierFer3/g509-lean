"""Generates G509/ExhaustData.lean (encoded integer boxes, adjacency lists) and G509/X/R<k>.lean (chunks of
rows) for the proof that the edge list of G509 is exhaustive.
The boxes are recomputed here in Python with the SAME formulas as lo3/hi3 of G509/Distinct.lean; the kernel
checks `boxes = pts.map boxOf` anyway (G509/Exhaust.lean), so an error here would make the
compilation fail, but could not make the theorem wrong.
Usage: python3 gen/gen_exhaust.py   (reads G509/Data.lean)"""
# License header written at the top of each generated Lean file.
HEADER = '/-\nCopyright (c) 2026 olivierFer3. All rights reserved.\nReleased under Apache 2.0 license as described in the file LICENSE.\nAuthors: olivierFer3 (code produced with Claude Code; see PROVENANCE.md)\n-/\n'
import re, os
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
src = open(R + "/G509/Data.lean").read()
pc = src[src.index("def ptsCode"):src.index("def pts :")]
codes = [int(x) for x in re.findall(r"\d{10,}", pc)]
es = src[src.index("def edges"):src.index("theorem pts_length")]
edges = [(int(a), int(b)) for a, b in re.findall(r"\((\d+), (\d+)\)", es)]
assert len(codes) == 509 and len(edges) == 2442
dig = lambda n, k: ((n // 512 ** k) % 512) - 256
def dec3(n, k): return [dig(n, k + i) for i in range(8)]
L = [1732050807, 2236067977, 3872983346, 3316624790, 5744562646, 7416198487, 12845232578]
tlo = lambda c, l: c * l if c >= 0 else c * (l + 1)
thi = lambda c, l: c * (l + 1) if c >= 0 else c * l
lo3 = lambda x: x[0] * 10**9 + sum(tlo(c, l) for c, l in zip(x[1:], L))
hi3 = lambda x: x[0] * 10**9 + sum(thi(c, l) for c, l in zip(x[1:], L))
OFF = 2 ** 40
B = []
for n in codes:
    x, y = dec3(n, 0), dec3(n, 8); b = (lo3(x), hi3(x), lo3(y), hi3(y))
    assert all(0 <= v + OFF < 2 ** 41 for v in b); B.append(tuple(v + OFF for v in b))
# order of `edges` = lexicographic order, and "upward" adjacency
assert edges == sorted(edges) and all(a < b for a, b in edges)
adj = [[] for _ in range(509)]
for a, b in edges: adj[a].append(b)
assert [(i, j) for i in range(509) for j in adj[i]] == edges
out = [HEADER + "/-! Data for the exhaustiveness of the edges, generated by",
       "`gen/gen_exhaust.py`. Boxes = (lo3 x, hi3 x, lo3 y, hi3 y) + 2^40. -/", "",
       "namespace G509.EX", "", "def boxesN : List (Nat × Nat × Nat × Nat) := ["]
out.append(",\n".join("  (%d, %d, %d, %d)" % b for b in B) + "]")
out += ["", "def adjN : List (List Nat) := ["]
out.append(",\n".join("  [%s]" % ", ".join(map(str, a)) for a in adj) + "]")
out += ["", "end G509.EX", ""]
open(R + "/G509/ExhaustData.lean", "w").write("\n".join(out))
os.makedirs(R + "/G509/X", exist_ok=True)
NCH, W = 16, 32
for k in range(NCH):
    open(R + "/G509/X/R%d.lean" % k, "w").write(
        HEADER + "import G509.Exhaust\n\n/-! Exhaustiveness, chunk %d of the rows (rows %d to %d). -/\n\n"
        "namespace G509.EX\n\ntheorem rows_%d : rowsOK (boxes.drop %d) %d (adjN.drop %d) %d = true := by decide +kernel\n\n"
        "end G509.EX\n" % (k, W * k, min(W * k + W, 509) - 1, k, W * k, W * k, W * k, W))
print("ok", len(B), "boxes;", NCH, "chunks")
