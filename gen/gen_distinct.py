import json, sys
from math import isqrt
root = sys.argv[1]; q = int(sys.argv[2]); M = 10**9
d = json.load(open(root + '/gen/g509.json')); pts = d['pts']
B = [1, 3, 5, 15, 11, 33, 55, 165]
L = [isqrt(M * M * b) for b in B]          # L ≤ M√b < L+1
def lo3(c): return sum(ck * L[k] if ck >= 0 else ck * (L[k] + 1) for k, ck in enumerate(c))
def hi3(c): return sum(ck * (L[k] + 1) if ck >= 0 else ck * L[k] for k, ck in enumerate(c))
iv = [(q * lo3(X) + lo3(Y), q * hi3(X) + hi3(Y)) for X, Y in pts]
sig = sorted(range(len(pts)), key=lambda i: iv[i][0])
ok = all(iv[sig[k]][1] < iv[sig[k + 1]][0] for k in range(len(sig) - 1))
gap = min(iv[sig[k + 1]][0] - iv[sig[k]][1] for k in range(len(sig) - 1))
print('q', q, 'L', L, 'ok', ok, 'min gap', gap)
if ok and len(sys.argv) > 3:
    with open(root + '/G509/DistinctData.lean', 'w') as f:
        f.write(HEADER + '/-! Permutation of the 509 indices by increasing key (generated by gen/gen_distinct.py). -/\n\n'
                'namespace G509\n\ndef sigma : List Nat := [\n')
        f.write(',\n'.join('  ' + ', '.join(map(str, sig[k:k + 20])) for k in range(0, len(sig), 20)))
        f.write(']\n\ndef sqrtLo : List Int := [%s]\n\ndef keyQ : Int := %d\n\nend G509\n' % (', '.join(map(str, L)), q))
