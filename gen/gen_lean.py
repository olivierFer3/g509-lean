"""Writes G509/Data.lean and G509/EdgesK.lean from gen/g509.json (output of gen_g509.py).
Usage: python3 gen/gen_lean.py . 12"""
# License header written at the top of each generated Lean file.
HEADER = '/-\nCopyright (c) 2026 olivierFer3. Released under Apache 2.0 license as described in the file LICENSE.\nAuthors: olivierFer3 (code produced with Claude Code; see PROVENANCE.md)\n-/\n'
import json, sys
root = sys.argv[1]; nchunks = int(sys.argv[2])
d = json.load(open(root + '/gen/g509.json'))
assert d['D'] == 96
pts, E = d['pts'], d['edges']
def enc(c):
    assert len(c) == 16 and all(abs(x) < 256 for x in c)
    n = 0
    for x in reversed(c): n = n * 512 + (x + 256)
    return n
DECODE = """/-- Coefficient number `k` (base 512, offset 256). -/
def dig (n k : ℕ) : ℤ := ((n / 512 ^ k) % 512 : ℕ) - 256

def decodeQ3 (n k : ℕ) : Q3 :=
  (((dig n k, dig n (k+1)), (dig n (k+2), dig n (k+3))),
   ((dig n (k+4), dig n (k+5)), (dig n (k+6), dig n (k+7))))

def decodePt (n : ℕ) : Pt := (decodeQ3 n 0, decodeQ3 n 8)

"""
def q3(a):
    return '(((%d, %d), (%d, %d)), ((%d, %d), (%d, %d)))' % tuple(a)
with open(root + '/G509/Data.lean', 'w') as f:
    f.write(HEADER + 'import G509.Field\n\n/-! Exact data of G509 (Parts), generated by `gen/gen_lean.py` from `vtx/509_parts.vtx`.\n'
            'Coordinates multiplied by 96, basis 1, √3, √5, √15, √11, √33, √55, √165 (nested). -/\n\n'
            'namespace G509\n\n')
    f.write(DECODE)
    f.write('/-- The 509 points of Parts (coordinates × 96), encoded in base 512 (offset 256). -/\n'
            'def ptsCode : List ℕ := [\n')
    f.write(',\n'.join('  %d' % enc(X + Y) for X, Y in pts))
    f.write(']\n\n/-- The 509 points. -/\ndef pts : List Pt := ptsCode.map decodePt\n\n')
    f.write('/-- The %d unit edges (pairs i < j). -/\ndef edges : List (ℕ × ℕ) := [\n' % len(E))
    lines = []
    for k in range(0, len(E), 12):
        lines.append('  ' + ', '.join('(%d, %d)' % tuple(e) for e in E[k:k+12]))
    f.write(',\n'.join(lines) + ']\n\n')
    f.write('theorem pts_length : pts.length = 509 := by decide +kernel\n')
    f.write('theorem edges_length : edges.length = %d := by decide +kernel\n\n' % len(E))
    f.write('/-- Point number `i` in `ℂ`. -/\nnoncomputable def P (i : ℕ) : ℂ := (pts.getD i default).toC\n\n')
    f.write('def edgeOK (e : ℕ × ℕ) : Bool := Pt.isUnit (pts.getD e.1 default) (pts.getD e.2 default)\n\n')
    f.write('end G509\n')
size = (len(E) + nchunks - 1) // nchunks
for k in range(nchunks):
    a, b = k * size, min(len(E), (k + 1) * size)
    with open(root + '/G509/Edges%d.lean' % k, 'w') as f:
        f.write(HEADER + 'import G509.Data\n\n/-! Kernel check (`decide +kernel`) of edges %d to %d. -/\n\n'
                'namespace G509\n\n' % (a, b - 1))
        f.write('theorem edges_ok_%d : ((edges.drop %d).take %d).all edgeOK = true := by decide +kernel\n\n' % (k, a, size))
        f.write('end G509\n')
print('chunks of', size)
